// Build-time tool: writes a .cpp holding files as byte arrays, so
// anton-gui carries its fonts in the binary (an install is one file).
//   embed out.cpp name1 file1 [name2 file2 ...]
// defines `extern const unsigned char name[]; extern const unsigned name_size;`
#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main(int argc, char** argv) {
  if (argc < 4 || argc % 2 != 0) {
    std::fprintf(stderr, "usage: embed out.cpp name file [name file ...]\n");
    return 2;
  }
  std::ofstream out(argv[1], std::ios::trunc);
  out << "// Generated by cmake/embed.cpp; do not edit.\n";
  for (int i = 2; i + 1 < argc; i += 2) {
    std::ifstream in(argv[i + 1], std::ios::binary);
    if (!in) {
      std::fprintf(stderr, "embed: can't read %s\n", argv[i + 1]);
      return 1;
    }
    std::vector<unsigned char> bytes((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    out << "extern const unsigned char " << argv[i] << "[];\n";
    out << "extern const unsigned " << argv[i] << "_size;\n";
    out << "const unsigned " << argv[i] << "_size = " << bytes.size() << ";\n";
    out << "alignas(4) const unsigned char " << argv[i] << "[] = {";
    for (size_t b = 0; b < bytes.size(); ++b) out << (b % 24 ? "" : "\n") << static_cast<int>(bytes[b]) << ',';
    out << "\n};\n";
  }
  return out ? 0 : 1;
}
